def rounded(x, y, w, h, r=2):
    return box(x+r, y+r, x+w-r, y+h-r).buffer(r, quad_segs=8)

class Solid:
    def __init__(self, mesh, source):
        self.mesh, self.source = mesh, source
    def __add__(self, other):
        return Solid(self.mesh + other.mesh, 'union(){\n'+self.source+other.source+'}\n')
    def __sub__(self, other):
        return Solid(self.mesh - other.mesh, 'difference(){\n'+self.source+other.source+'}\n')
    def move(self, xyz):
        return Solid(self.mesh.translate(xyz), f'translate({list(xyz)}){{\n{self.source}}}\n')
    def rotate(self, z):
        return Solid(self.mesh.rotate([0,0,z]),f'rotate([0,0,{z}]){{\n{self.source}}}\n')

def union(parts):
    parts=list(parts)
    return Solid(mf.Manifold.batch_boolean([s.mesh for s in parts],mf.OpType.Add),
                 'union(){\n'+''.join(s.source for s in parts)+'}\n')

def extrude(geom,h,z=0):
    if geom.geom_type=='MultiPolygon':
        return union(extrude(g,h,z) for g in geom.geoms)
    rings=[list(geom.exterior.coords)[:-1]]+[list(r.coords)[:-1] for r in geom.interiors]
    # EvenOdd accepts Shapely's ring windings without silently filling holes.
    cs=mf.CrossSection(rings,mf.FillRule.EvenOdd)
    points=[];paths=[]
    for ring in rings:
        paths.append(list(range(len(points),len(points)+len(ring))))
        points.extend([[round(x,6),round(y,6)] for x,y in ring])
    src=f'linear_extrude(height={h}) polygon(points={json.dumps(points)},paths={json.dumps(paths)});\n'
    return Solid(cs.extrude(h),src).move((0,0,z))

def cyl(x,y,z,h,d,d2=None):
    mesh=mf.Manifold.cylinder(h,d/2,(d if d2 is None else d2)/2,circular_segments=64)
    src=f'cylinder(h={h},d1={d},d2={d if d2 is None else d2},$fn=64);\n'
    return Solid(mesh,src).move((x,y,z))

def pocket(x,y,top,diam=None):
    d=P['insert_pocket_diameter'] if diam is None else diam
    depth=P['insert_length']+P['insert_depth_allowance']
    return cyl(x,y,top-depth,depth+EPS,d) + cyl(x,y,top-.45,.45+EPS,d,d+.8)

def output(name,s,expected=1):
    m=s.mesh.to_mesh()
    tm=trimesh.Trimesh(vertices=np.asarray(m.vert_properties)[:,:3],faces=np.asarray(m.tri_verts),process=True)
    assert str(s.mesh.status())=='Error.NoError',(name,s.mesh.status())
    assert tm.is_watertight and tm.is_winding_consistent,(name,'non-watertight mesh')
    assert len(s.mesh.decompose())==expected,(name,'unexpected disconnected body count')
    assert tm.volume>0
    assert tm.bounds[0,2]>=-1e-6
    tm.export(OUT/(name+'.stl'))
    (OUT/(name+'.scad')).write_text('// Generated by build_mount.py; source parameters are ../parameters.json.\n// Dimensions in mm. Original printed geometry only.\n'+s.source)
    return {'file':name+'.stl','watertight':bool(tm.is_watertight),'winding_consistent':bool(tm.is_winding_consistent),
            'bodies':len(s.mesh.decompose()),'triangles':len(tm.faces),'bounds_mm':tm.bounds.tolist(),
            'dimensions_mm':tm.extents.tolist(),'volume_cm3':float(tm.volume/1000)}

