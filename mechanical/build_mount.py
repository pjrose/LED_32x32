def svg_poly(g,fill,stroke='#62768a',sw=.35,opacity=1):
    geoms=list(g.geoms) if g.geom_type=='MultiPolygon' else [g]
    paths=[]
    for gg in geoms:
        rings=[gg.exterior]+list(gg.interiors)
        path=' '.join('M '+' L '.join(f'{x:.3f},{S-y:.3f}' for x,y in ring.coords)+' Z' for ring in rings)
        paths.append(f'<path d="{path}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}" fill-rule="evenodd" opacity="{opacity}"/>')
    return ''.join(paths)

